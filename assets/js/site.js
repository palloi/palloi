const storageKey = "palloi-lang";
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

const getLang = () => {
  const saved = localStorage.getItem(storageKey);
  if (saved === "pt" || saved === "en") return saved;
  return "pt";
};

const setDocumentMeta = (lang) => {
  const t = translations[lang];
  document.documentElement.lang = lang === "en" ? "en" : "pt-BR";
  document.title = t["doc.title"];
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", t["doc.description"]);
  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute("content", t["doc.title"]);
  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (ogDescription) ogDescription.setAttribute("content", t["doc.description"]);
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute("content", lang === "en" ? "en_US" : "pt_BR");
};

const applyTranslations = (lang) => {
  const t = translations[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key]) el.textContent = t[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (t[key]) el.setAttribute("aria-label", t[key]);
  });
  setDocumentMeta(lang);
  document.querySelectorAll("[data-lang-set]").forEach((btn) => {
    const active = btn.getAttribute("data-lang-set") === lang;
    btn.setAttribute("aria-pressed", String(active));
    btn.classList.toggle("is-active", active);
  });
  localStorage.setItem(storageKey, lang);
};

const setupLanguage = () => {
  applyTranslations(getLang());
  document.querySelectorAll("[data-lang-set]").forEach((btn) => {
    btn.addEventListener("click", () => applyTranslations(btn.getAttribute("data-lang-set")));
  });
};

const setupMenu = () => {
  const toggle = document.querySelector("[data-menu-toggle]");
  const panel = document.querySelector("[data-menu-panel]");
  const links = panel ? panel.querySelectorAll("a") : [];
  if (!toggle || !panel) return;

  const setOpen = (open) => {
    toggle.setAttribute("aria-expanded", String(open));
    panel.classList.toggle("hidden", !open);
    document.body.classList.toggle("menu-open", open);
    const labelKey = open ? "nav.close" : "nav.open";
    const lang = getLang();
    toggle.setAttribute("aria-label", translations[lang][labelKey]);
    toggle.setAttribute("data-i18n-aria", labelKey);
  };

  toggle.addEventListener("click", () => {
    const open = toggle.getAttribute("aria-expanded") !== "true";
    setOpen(open);
  });

  links.forEach((link) => link.addEventListener("click", () => setOpen(false)));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") setOpen(false);
  });
};

const setupReveal = () => {
  const items = document.querySelectorAll("[data-reveal]");
  if (reduceMotion || !("IntersectionObserver" in window)) {
    items.forEach((el) => el.classList.add("is-visible"));
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );

  items.forEach((el) => observer.observe(el));
};

const setupScrollSpy = () => {
  const links = [...document.querySelectorAll("[data-nav-link]")];
  const sections = links
    .map((link) => document.querySelector(link.getAttribute("href")))
    .filter(Boolean);
  if (!sections.length) return;

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const id = `#${entry.target.id}`;
        links.forEach((link) => {
          link.classList.toggle("is-current", link.getAttribute("href") === id);
        });
      });
    },
    { rootMargin: "-40% 0px -50% 0px", threshold: 0 }
  );

  sections.forEach((section) => observer.observe(section));
};

const setupYear = () => {
  const el = document.querySelector("[data-year]");
  if (el) el.textContent = String(new Date().getFullYear());
};

const scrollToHash = () => {
  const id = decodeURIComponent(location.hash.replace("#", ""));
  if (!id) return;
  const target = document.getElementById(id);
  if (target) target.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "start" });
};

setupLanguage();
setupMenu();
setupReveal();
setupScrollSpy();
setupYear();

if (location.hash) {
  window.addEventListener("load", () => {
    window.setTimeout(scrollToHash, 80);
  });
}
